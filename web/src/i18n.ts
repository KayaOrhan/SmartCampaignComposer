export type MessageKey = keyof typeof turkish
export type Locale = 'en' | 'tr'
export const locale = ref<Locale>('en')
watch(locale, value => { document.documentElement.lang = value }, { immediate: true })
export function setLocale(value: string) { locale.value = value === 'tr' ? 'tr' : 'en' }
export function t(key: MessageKey | '', values: Record<string, string | number> = {}): string {
  const text = key ? (locale.value === 'tr' ? turkish[key] : key) : ''
  return text.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(values, name) ? String(values[name]) : match)
}
const intlLocale = () => locale.value === 'tr' ? 'tr-TR' : 'en-US'
export const number = (value: number) => new Intl.NumberFormat(intlLocale()).format(value)
function formatDate(value: string | Date, options: Intl.DateTimeFormatOptions) {
  const parsed = new Date(value)
  return Number.isNaN(parsed.getTime()) ? '—' : new Intl.DateTimeFormat(intlLocale(), options).format(parsed)
}
export const date = (value: string | Date) => formatDate(value, { dateStyle: 'short' })
export const dateTime = (value: string | Date) => formatDate(value, { dateStyle: 'short', timeStyle: 'medium' })
export const time = (value: string | Date) => formatDate(value, { timeStyle: 'medium' })
export const channelLabel = (channel: Channel) => t(channel === 'sms' ? 'SMS' : 'Email')
