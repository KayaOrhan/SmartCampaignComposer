import { test, expect } from '@playwright/test'

test('create, generate, edit, review, approve and finish mock delivery', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Campaign brief').fill('A friendly 30% discount for Istanbul customers with carts but no purchases in the last 30 days.')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Make it meaningful.' })).toBeVisible()
  await page.getByRole('button', { name: 'Generate segment', exact: true }).click()
  await expect(page.getByText('City is istanbul', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Preview audience', exact: true }).click()
  await expect(page.getByText('Unique recipients', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Generate messages', exact: true }).click()
  await expect(page.getByText(/Streaming preview/)).toBeVisible()
  await expect(page.getByText('Validated suggestion · not saved.', { exact: false })).toBeVisible({ timeout: 35000 })
  await expect(page.getByRole('button', { name: 'Approve & start mock delivery', exact: true })).toBeDisabled()
  await page.getByLabel('SMS message', { exact: true }).fill('Hello {{first_name}}, your 30% offer is waiting. Shop today!')
  await page.getByLabel('Email subject', { exact: true }).fill('A little something for {{first_name}}')
  await page.getByRole('button', { name: 'Save messages', exact: true }).click()
  await expect(page.getByText(/Saved and validated at revision/)).toBeVisible()
  await page.getByRole('button', { name: 'Review current audience', exact: true }).click()
  await page.getByRole('checkbox', { name: /I have reviewed/ }).check()
  await page.getByRole('button', { name: 'Approve & start mock delivery', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Delivery dashboard' })).toBeVisible()
  await expect(page.getByText(/Campaign completed. All jobs are terminal/)).toBeVisible({ timeout: 180000 })
  await expect(page.getByLabel('SMS message', { exact: true })).toBeDisabled()
  await expect(page.getByRole('progressbar')).toHaveAttribute('value', await page.getByRole('progressbar').getAttribute('max') ?? '')
  await page.screenshot({ path: 'test-results/completed-campaign.png', fullPage: true })
  await page.getByRole('button', { name: 'All campaigns' }).click()
  await page.getByRole('button', { name: 'View metrics' }).click()
  await expect(page.locator('.metric-text')).toContainText('llm_calls_total')
  expect(errors).toEqual([])
})

test('a concurrent save requires reconciliation, not a silent retry', async ({ page, request }) => {
  await page.goto('/')
  await page.getByLabel('Campaign brief').fill('Synthetic conflict test: friendly Istanbul offer')
  await page.getByLabel('Email', { exact: false }).uncheck()
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/campaigns') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  const created = await (await responsePromise).json()
  await page.getByRole('button', { name: 'Generate segment', exact: true }).click()
  await page.getByRole('button', { name: 'Generate messages', exact: true }).click()
  await expect(page.getByText('Validated suggestion · not saved.', { exact: false })).toBeVisible({ timeout: 35000 })
  const current = await (await request.get(`/api/campaigns/${created.id}`)).json()
  const competing = await request.put(`/api/campaigns/${created.id}/messages`, { headers: { 'If-Match': `"campaign-${created.id}-r${current.revision}"` }, data: { messages: { sms: { body: 'A competing reviewed edit' } } } })
  expect(competing.status()).toBe(200)
  await page.getByLabel('SMS message', { exact: true }).fill('My local draft')
  await page.getByRole('button', { name: 'Save messages', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('review again')
  await expect(page.getByRole('button', { name: 'Save messages', exact: true })).toBeDisabled()
  await expect(page.getByLabel('SMS message', { exact: true })).toHaveValue('My local draft')
  await page.getByRole('button', { name: 'Discard local changes and reload', exact: true }).first().click()
  await expect(page.getByLabel('SMS message', { exact: true })).toHaveValue('A competing reviewed edit')
  await expect(page.getByRole('checkbox', { name: /I have reviewed/ })).not.toBeChecked()
})

test('campaign list remains usable on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Campaigns', exact: true })).toBeVisible()
  await expect(page.getByLabel('Campaign brief')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/mobile-campaigns.png' })
})
