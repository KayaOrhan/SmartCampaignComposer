test('a concurrent save requires reconciliation, not a silent retry', async ({ page, request }) => {
  await page.goto('/')
  await page.getByLabel('Campaign brief').fill('Synthetic conflict test: friendly Istanbul offer')
  await page.getByLabel('Email', { exact: false }).uncheck()
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/campaigns') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Create campaign', exact: true }).click()
  const created = await (await responsePromise).json()
  await page.getByRole('button', { name: 'Generate segment', exact: true }).click()
  await page.getByRole('button', { name: 'Generate messages', exact: true }).click()
  await expect(page.getByText('Validated suggestion · not saved.', { exact: false })).toBeVisible({ timeout: 35000 })
  const current = await (await request.get(`/api/campaigns/${created.id}`)).json()
  const competing = await request.put(`/api/campaigns/${created.id}/messages`, { headers: { 'If-Match': `"campaign-${created.id}-r${current.revision}"` }, data: { messages: { sms: { body: 'A competing reviewed edit' } } } })
  expect(competing.status()).toBe(200)
  await page.getByLabel('SMS message', { exact: true }).fill('My local draft')
  await page.getByRole('button', { name: 'Save messages', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('review again')
  await expect(page.getByRole('button', { name: 'Save messages', exact: true })).toBeDisabled()
  await expect(page.getByLabel('SMS message', { exact: true })).toHaveValue('My local draft')
  await page.getByRole('button', { name: 'Discard local changes and reload', exact: true }).first().click()
  await expect(page.getByLabel('SMS message', { exact: true })).toHaveValue('A competing reviewed edit')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

