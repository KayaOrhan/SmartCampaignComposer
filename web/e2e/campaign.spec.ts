test('Swagger UI loads locally and resolves the OpenAPI contract', async ({ page }) => {
  const errors: string[] = [], remote: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:5173/')) remote.push(r.url()) })
  await page.goto('/docs/')
  await expect(page.getByRole('heading', { name: /Smart Campaign Composer API/ })).toBeVisible()
  await expect(page.locator('.opblock-summary-path').filter({ hasText: '/campaigns/{id}/approve' })).toBeVisible()
  await expect(page.locator('.errors-wrapper')).toHaveCount(0)
  await expect(page.getByText(/NO authentication or authorization/).first()).toBeVisible()
  const response = await page.request.get('/api/openapi.json')
  expect((await response.json()).openapi).toBe('3.2.1')
  await page.screenshot({ path: 'test-results/swagger-ui.png', fullPage: true })
  expect(errors).toEqual([])
  expect(remote).toEqual([])
})
