test('deletion requires confirmation, handles stale revisions, and removes only the draft', async ({ page, request }) => {
  const created = await (await request.post('/api/campaigns', { data: { brief: 'Synthetic browser deletion', channels: ['sms'] } })).json()
  await page.goto('/')
  await page.getByRole('button', { name: /Synthetic browser deletion/ }).first().click()
  await page.getByRole('button', { name: 'Delete draft', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Delete this draft campaign?' })
  await expect(dialog).toContainText('Stored content and audit records are retained')
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  expect((await request.get(`/api/campaigns/${created.id}`)).status()).toBe(200)
  await page.getByRole('button', { name: 'Delete draft', exact: true }).click()
  // A concurrent segment save invalidates the deletion token.
  const changed = await request.put(`/api/campaigns/${created.id}/segment`, { headers: { 'If-Match': `"campaign-${created.id}-r${created.revision}"` }, data: { version: 1, all: [{ field: 'city', op: 'in', value: ['istanbul'] }] } })
  expect(changed.status()).toBe(200)
  await dialog.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('campaign or audience changed')
  expect((await request.get(`/api/campaigns/${created.id}`)).status()).toBe(200)
  await page.getByRole('button', { name: 'Discard local changes and reload', exact: true }).first().click()
  await page.getByRole('button', { name: 'Delete draft', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Campaigns', exact: true })).toBeVisible()
  expect((await request.get(`/api/campaigns/${created.id}`)).status()).toBe(404)
  await expect(page.getByRole('button', { name: /Synthetic browser deletion/ })).toHaveCount(0)
})

test('review conflict requires another explicit review and never retries approval automatically', async ({ page, request }) => {
  const created = await (await request.post('/api/campaigns', { data: { brief: 'Synthetic browser review conflict', channels: ['sms'] } })).json()
  const segment = await request.put(`/api/campaigns/${created.id}/segment`, { headers: { 'If-Match': `"campaign-${created.id}-r${created.revision}"` }, data: { version: 1, all: [{ field: 'city', op: 'in', value: ['istanbul'] }] } })
  const segmented = await segment.json()
  const saved = await request.put(`/api/campaigns/${created.id}/messages`, { headers: { 'If-Match': `"campaign-${created.id}-r${segmented.revision}"` }, data: { messages: { sms: { body: 'Synthetic saved review template' } } } })
  expect(saved.status()).toBe(200)
  await page.goto('/')
  await page.getByRole('button', { name: /Synthetic browser review conflict/ }).first().click()
  await page.getByRole('button', { name: 'Review & approve', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Review campaign approval' })
  await expect(dialog).toContainText('Synthetic saved review template')
  let approvals = 0
  await page.route(`**/api/campaigns/${created.id}/approve`, route => { approvals++; return route.fulfill({ status: 409, json: { error: { code: 'approval_preview_changed', path: '$' } } }) })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/mobile-review-dialog.png', fullPage: true })
  await dialog.getByRole('button', { name: 'Confirm approval & start mock delivery', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('review again')
  await expect(dialog).not.toBeVisible()
  expect(approvals).toBe(1)
  await page.getByRole('button', { name: 'Discard local changes and reload', exact: true }).first().click()
  await page.getByRole('button', { name: 'Review & approve', exact: true }).click()
  await expect(dialog).toBeVisible()
  expect(approvals).toBe(1)
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  const current = await (await request.get(`/api/campaigns/${created.id}`)).json()
  expect(current.status).toBe('content_ready')
})


